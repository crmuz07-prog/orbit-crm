#!/usr/bin/env python3
"""Generates infra/asterisk/.env for the local test PBX.

Keeps existing SIP/AMI passwords, refreshes the Orbit webhook URL and secret from the API
(demo workspace by default; pass ORBIT_TOKEN=<jwt> to use your own workspace).
"""

import json
import os
import secrets
import subprocess
import urllib.request
from pathlib import Path

API = os.environ.get("ORBIT_API", "http://localhost:8000")
ENV_FILE = Path(__file__).resolve().parent.parent / "infra" / "asterisk" / ".env"


def api(method: str, path: str, token: str | None = None) -> dict:
    headers = {"Content-Type": "application/json", **({"Authorization": f"Bearer {token}"} if token else {})}
    with urllib.request.urlopen(urllib.request.Request(API + path, method=method, headers=headers)) as response:
        return json.loads(response.read())


def lan_ip() -> str:
    for interface in ("en0", "en1"):
        result = subprocess.run(["ipconfig", "getifaddr", interface], capture_output=True, text=True)
        if result.stdout.strip():
            return result.stdout.strip()
    raise SystemExit("Could not detect the LAN IP — set HOST_IP manually in infra/asterisk/.env")


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line and not line.startswith("#"))
    return {key: value for key, value in pairs}


def main() -> None:
    current = read_env()
    token = os.environ.get("ORBIT_TOKEN") or api("POST", "/api/auth/demo")["access_token"]
    telephony = api("GET", "/api/telephony", token)
    values = {
        "HOST_IP": os.environ.get("HOST_IP") or lan_ip(),
        "SIP_PASSWORD_101": current.get("SIP_PASSWORD_101") or secrets.token_urlsafe(12),
        "SIP_PASSWORD_102": current.get("SIP_PASSWORD_102") or secrets.token_urlsafe(12),
        "AMI_SECRET": current.get("AMI_SECRET") or secrets.token_urlsafe(16),
        # The bridge runs in Docker, so it reaches the API on the host through host.docker.internal.
        "ORBIT_WEBHOOK_URL": API.replace("localhost", "host.docker.internal").replace("127.0.0.1", "host.docker.internal") + telephony["webhook_path"],
        "ORBIT_SIGNING_SECRET": telephony["signing_secret"],
        "RECORDINGS_BASE_URL": "http://localhost:8090",
    }
    ENV_FILE.write_text("# Generated by scripts/pbx-env.py — do not commit.\n" + "".join(f"{k}={v}\n" for k, v in values.items()))
    os.chmod(ENV_FILE, 0o600)
    print(f"✓ {ENV_FILE.relative_to(Path.cwd()) if ENV_FILE.is_relative_to(Path.cwd()) else ENV_FILE}")
    print(f"  SIP server: {values['HOST_IP']}:5060 (UDP)")
    print("  Phone (Zoiper): user 102, password in infra/asterisk/.env → SIP_PASSWORD_102")


if __name__ == "__main__":
    main()
